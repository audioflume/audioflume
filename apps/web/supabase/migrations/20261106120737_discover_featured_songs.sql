create table if not exists public.discover_featured_songs (
  id bigint generated by default as identity primary key,
  song_id uuid not null references public.songs(id) on delete cascade,
  position integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  constraint discover_featured_songs_song_id_key unique (song_id)
);

create index if not exists discover_featured_songs_position_idx
  on public.discover_featured_songs (position);

alter table public.discover_featured_songs enable row level security;
