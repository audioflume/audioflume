-- Homepage carousel selections are independent from Discover featured artists.
create table if not exists public.home_featured_artists (
  id bigint generated by default as identity primary key,
  artist_id uuid not null references public.artists(id) on delete cascade,
  position integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  constraint home_featured_artists_artist_id_key unique (artist_id)
);

create index if not exists home_featured_artists_position_idx
  on public.home_featured_artists (position);

alter table public.home_featured_artists enable row level security;
