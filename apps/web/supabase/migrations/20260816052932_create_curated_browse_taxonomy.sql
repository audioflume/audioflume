create table if not exists public.curated_browse_subcategories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  constraint curated_browse_subcategories_slug_check
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint curated_browse_subcategories_label_check
    check (length(btrim(label)) > 0)
);

create table if not exists public.curated_browse_filter_subcategories (
  browse_filter text not null,
  subcategory_id bigint not null references public.curated_browse_subcategories(id) on delete cascade,
  position integer not null default 0,
  primary key (browse_filter, subcategory_id),
  constraint curated_browse_filter_subcategories_filter_check
    check (browse_filter in ('editors', 'mood', 'genre', 'brands', 'travel', 'documentary', 'cinematic', 'dark-moody'))
);

create table if not exists public.curated_playlist_browse_assignments (
  curated_playlist_id bigint not null references public.curated_playlists(id) on delete cascade,
  browse_filter text not null,
  subcategory_id bigint not null,
  primary key (curated_playlist_id, browse_filter, subcategory_id),
  constraint curated_playlist_browse_assignments_filter_check
    check (browse_filter in ('editors', 'mood', 'genre', 'brands', 'travel', 'documentary', 'cinematic', 'dark-moody')),
  constraint curated_playlist_browse_assignments_taxonomy_fkey
    foreign key (browse_filter, subcategory_id)
    references public.curated_browse_filter_subcategories(browse_filter, subcategory_id)
    on delete cascade
);

create index if not exists curated_browse_filter_subcategories_subcategory_idx
  on public.curated_browse_filter_subcategories(subcategory_id);

create index if not exists curated_playlist_browse_assignments_filter_subcategory_idx
  on public.curated_playlist_browse_assignments(browse_filter, subcategory_id);

alter table public.curated_browse_subcategories enable row level security;
alter table public.curated_browse_filter_subcategories enable row level security;
alter table public.curated_playlist_browse_assignments enable row level security;

grant select, insert, update, delete on table public.curated_browse_subcategories to service_role;
grant select, insert, update, delete on table public.curated_browse_filter_subcategories to service_role;
grant select, insert, update, delete on table public.curated_playlist_browse_assignments to service_role;
grant usage, select on sequence public.curated_browse_subcategories_id_seq to service_role;

