insert into public.curated_browse_filter_subcategories (browse_filter, subcategory_id, position)
select mappings.browse_filter, subcategory.id, mappings.position
from mappings
join public.curated_browse_subcategories as subcategory
  on subcategory.slug = mappings.slug
on conflict (browse_filter, subcategory_id) do update
set position = excluded.position;

with legacy_values as (
  select
    playlist.id as curated_playlist_id,
    playlist.browse_tags,
    item.value as raw_value,
    case
      when item.value = 'editors:social-short-form' then 'film-story'
      when position(':' in item.value) > 0 then split_part(item.value, ':', 2)
      else item.value
    end as slug,
    case
      when position(':' in item.value) > 0 then split_part(item.value, ':', 1)
      else null
    end as legacy_filter
  from public.curated_playlists as playlist
  cross join lateral unnest(playlist.browse_subcategories) as item(value)
)
insert into public.curated_playlist_browse_assignments (
  curated_playlist_id,
  browse_filter,
  subcategory_id
)
select distinct
  legacy.curated_playlist_id,
  mapping.browse_filter,
  subcategory.id
from legacy_values as legacy
join public.curated_browse_subcategories as subcategory
  on subcategory.slug = legacy.slug
join public.curated_browse_filter_subcategories as mapping
  on mapping.subcategory_id = subcategory.id
 and (
   (legacy.legacy_filter is not null and mapping.browse_filter = legacy.legacy_filter)
   or
   (legacy.legacy_filter is null and mapping.browse_filter = any(legacy.browse_tags))
 )
on conflict do nothing;
